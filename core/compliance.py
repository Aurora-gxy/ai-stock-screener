"""合规边界（确定性规则，不依赖 LLM）。

1. 输入侧：识别「预测涨跌 / 收益承诺 / 直接买卖建议 / 内幕消息 / 个人持仓隐私」类诉求，
   明确告知不提供，只保留其中可转化为客观筛选条件的部分。
2. 输出侧：对 AI 生成的文字做审查，命中违规表述时替换并标记。
"""
from __future__ import annotations

import re

DISCLAIMER = ("本工具仅根据公开数据和用户设定的条件做客观筛选与解释，不构成投资建议，"
              "不预测股价涨跌，不承诺收益。历史数据不代表未来表现。")

INPUT_RULES = [
    (r"(明天|下周|未来|接下来|后市|短期内?).{0,6}(会|能|将|要)?.{0,2}(涨|跌|翻倍|大涨|暴涨)|涨停.{0,4}(股|票)|预测.{0,6}(涨|跌|股价|走势)|会不会涨|能涨到|目标价",
     "预测", "本产品不提供股价涨跌预测或目标价。可以帮你按客观条件（如近期走势、波动率）筛选。"),
    (r"(稳赚|保本|保证.{0,4}收益|收益率?.{0,4}(保证|承诺)|无风险|必赚|一定.{0,3}(赚|涨)|翻倍)",
     "收益承诺", "本产品不承诺任何收益，所有结果仅为条件筛选，存在亏损风险。"),
    (r"(该|应该|帮我|直接|推荐).{0,4}(买|卖|买入|卖出|抄底|清仓|加仓|满仓)|(买哪[只个支]|卖哪[只个支])|买点|卖点",
     "买卖建议", "本产品不提供买卖建议，只返回满足你所设条件的候选清单及依据，决策请自行判断。"),
    (r"(内幕|小道消息|庄家.{0,4}(拉升|操纵)|操纵股价)",
     "违规信息", "本产品不处理内幕信息或市场操纵相关诉求。"),
    (r"(身份证|银行卡号|手机号|证券账户|资金账号|密码)",
     "隐私", "请勿输入身份证、账户、密码等个人敏感信息，本产品不需要也不会保存这些信息。"),
]

OUTPUT_BANNED = [
    (r"(建议|推荐)(你|您)?(买入|卖出|增持|减持|持有|抄底|加仓)", "［已移除：买卖建议］"),
    (r"(必涨|必然上涨|一定会?涨|稳赚|保证收益|无风险)", "［已移除：确定性表述］"),
    (r"(将|会|有望)(大幅)?(上涨|下跌|反弹|走高|走低)", "［已移除：涨跌预测］"),
    (r"目标价[^，。；]*", "［已移除：价位目标］"),
]


def check_input(text: str) -> list[dict]:
    hits = []
    for pat, kind, msg in INPUT_RULES:
        m = re.search(pat, text or "")
        if m:
            hits.append({"type": kind, "matched": m.group(0), "message": msg})
    return hits


def sanitize_output(text: str) -> tuple[str, list[str]]:
    flags = []
    out = text or ""
    for pat, rep in OUTPUT_BANNED:
        if re.search(pat, out):
            flags.append(rep)
            out = re.sub(pat, rep, out)
    return out, flags
